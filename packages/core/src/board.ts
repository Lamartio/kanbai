import { type BoardConfig } from './config.js';
import { type Issue, type ParseResult, parseIssue } from './issue.js';
import { MAIN_BOARD, boardFileRelativePath, classifyPath, formatId, isBoardName, newIssueRelativePath } from './naming.js';

/** The text files of a repo the board needs: `.board.json` plus the markdown in the docs folder. */
export interface Snapshot {
  /** Commit the files were read from. */
  commit: string;
  /** Path relative to the repo root → file text. */
  files: Record<string, string>;
  /** Folders that exist in the repo (relative paths, no trailing slash). */
  dirs?: string[];
}

/** A file to write (`content`) or delete (`content: null`), relative to the repo root. */
export interface FileChange {
  path: string;
  content: string | null;
}

export interface BoardInfo {
  /** '' for the main board. */
  name: string;
  /** True when the board has its own folder (`BOARD/`) inside the board folder. */
  hasFolder: boolean;
  /** Repo path of its generated board file. */
  filePath: string;
  /** Current text of that file, if it exists. */
  text?: string;
  /** Other board files for this board (a leftover `BOARD_000_board.md` next to `BOARD/000_board.md`). */
  extraFiles: string[];
}

export interface LoadedBoard {
  issues: Issue[];
  /** Markdown files in the board folder that couldn't be read as issues. */
  invalid: Extract<ParseResult, { ok: false }>[];
  boards: Map<string, BoardInfo>;
  /** Highest number seen per board, from file names alone (so broken files count too). */
  highest: Map<string, number>;
}

function boardFolders(snapshot: Snapshot, config: BoardConfig): Set<string> {
  const folders = new Set<string>();
  const prefix = `${config.board}/`;
  const consider = (path: string) => {
    if (!path.startsWith(prefix)) return;
    const first = path.slice(prefix.length).split('/')[0]!;
    if (path.slice(prefix.length).includes('/') && isBoardName(first) && !first.includes('_')) folders.add(first);
  };
  for (const path of Object.keys(snapshot.files)) consider(path);
  for (const dir of snapshot.dirs ?? []) consider(`${dir}/`);
  return folders;
}

export function loadBoard(snapshot: Snapshot, config: BoardConfig): LoadedBoard {
  const issues: Issue[] = [];
  const invalid: LoadedBoard['invalid'] = [];
  const highest = new Map<string, number>([[MAIN_BOARD, 0]]);
  const folders = boardFolders(snapshot, config);
  const boardFiles = new Map<string, string[]>();
  const prefix = `${config.board}/`;

  for (const [path, text] of Object.entries(snapshot.files)) {
    if (!path.startsWith(prefix) || !path.endsWith('.md')) continue;
    const kind = classifyPath(path.slice(prefix.length));
    if (kind.kind === 'board-file') {
      boardFiles.set(kind.board, [...(boardFiles.get(kind.board) ?? []), path]);
      continue;
    }
    if (kind.kind === 'other') continue;
    if (kind.kind === 'invalid') {
      invalid.push({ ok: false, path, error: kind.reason });
      continue;
    }
    const { board, number } = kind.location;
    highest.set(board, Math.max(highest.get(board) ?? 0, number));
    const result = parseIssue(path, text, config.board);
    if (result.ok) issues.push(result.issue);
    else invalid.push(result);
  }
  issues.sort((a, b) => a.board.localeCompare(b.board) || a.number - b.number || a.path.localeCompare(b.path));

  const names = new Set<string>([MAIN_BOARD, ...folders, ...boardFiles.keys(), ...issues.map((issue) => issue.board)]);
  const boards = new Map<string, BoardInfo>();
  for (const name of names) {
    const hasFolder = folders.has(name);
    const filePath = `${config.board}/${boardFileRelativePath(name, hasFolder)}`;
    boards.set(name, {
      name,
      hasFolder,
      filePath,
      text: snapshot.files[filePath],
      extraFiles: (boardFiles.get(name) ?? []).filter((path) => path !== filePath),
    });
    if (!highest.has(name)) highest.set(name, 0);
  }
  return { issues, invalid, boards, highest };
}

export function getBoard(loaded: LoadedBoard, config: BoardConfig, name: string): BoardInfo {
  return (
    loaded.boards.get(name) ?? {
      name,
      hasFolder: false,
      filePath: `${config.board}/${boardFileRelativePath(name, false)}`,
      extraFiles: [],
    }
  );
}

/** Repo path for a new issue. */
export function newIssuePath(loaded: LoadedBoard, config: BoardConfig, board: string, number: number, slug: string, parent?: Issue): string {
  const parentRelative = parent ? parent.path.slice(config.board.length + 1) : undefined;
  return `${config.board}/${newIssueRelativePath({ board, number, slug, parentRelative, boardHasFolder: getBoard(loaded, config, board).hasFolder })}`;
}

const laneTitle = (lane: string) => lane.charAt(0).toUpperCase() + lane.slice(1).replace(/-/g, ' ');

export const GENERATED_NOTE = "<!-- Generated by kanbai from the issues' frontmatter. Do not edit by hand: run the doctor instead. -->";

function relativeLink(fromFile: string, toFile: string): string {
  const from = fromFile.split('/').slice(0, -1);
  const to = toFile.split('/');
  let common = 0;
  while (common < from.length && common < to.length - 1 && from[common] === to[common]) common++;
  const up = from.length - common;
  return `${up ? '../'.repeat(up) : './'}${to.slice(common).join('/')}`;
}

/**
 * Renders one board file: a header per lane, a bullet per issue. Sub-issues aren't listed;
 * they live in their parent's folder. Issues in unknown lanes go under "Unsorted".
 */
export function renderBoard(issues: Issue[], config: BoardConfig, board: BoardInfo): string {
  const byLane = new Map<string, Issue[]>(config.lanes.map((lane) => [lane, []]));
  const unsorted: Issue[] = [];
  for (const issue of issues) {
    if (issue.board !== board.name || issue.parentPath) continue;
    const lane = byLane.get(issue.frontmatter.status);
    if (lane) lane.push(issue);
    else unsorted.push(issue);
  }
  const bullet = (issue: Issue) => {
    const extra = [issue.frontmatter.assignee ? `@${issue.frontmatter.assignee}` : '', ...issue.frontmatter.tags.map((tag) => `#${tag}`)]
      .filter(Boolean)
      .join(' ');
    return `- [${formatId(issue.board, issue.number)} ${issue.frontmatter.title || issue.slug}](${relativeLink(board.filePath, issue.path)})${extra ? ` ${extra}` : ''}`;
  };
  const sortByNumber = (list: Issue[]) => [...list].sort((a, b) => a.number - b.number);
  const parts = [`# ${board.name || 'Board'}`, GENERATED_NOTE];
  for (const [lane, laneIssues] of byLane) {
    parts.push(`## ${laneTitle(lane)}`, laneIssues.length ? sortByNumber(laneIssues).map(bullet).join('\n') : '_Empty_');
  }
  if (unsorted.length) parts.push('## Unsorted', sortByNumber(unsorted).map(bullet).join('\n'));
  return `${parts.join('\n\n')}\n`;
}

/** Board files that change when `changed` issues are written (or that are out of date anyway). */
export function boardChanges(loaded: LoadedBoard, config: BoardConfig, changed: Issue[], onlyBoards?: Iterable<string>): FileChange[] {
  const byPath = new Map(loaded.issues.map((issue) => [issue.path, issue]));
  for (const issue of changed) byPath.set(issue.path, issue);
  const all = [...byPath.values()];
  const targets = new Set(onlyBoards ?? changed.map((issue) => issue.board));
  const changes: FileChange[] = [];
  for (const name of targets) {
    const board = getBoard(loaded, config, name);
    const next = renderBoard(all, config, board);
    if (next !== board.text) changes.push({ path: board.filePath, content: next });
  }
  return changes;
}
